package ports

import (
	"context"
	"time"

	"github.com/fleet-platform/backend/internal/worker/domain"
)

// PositionRepository persists validated positions in the telemetry.positions hypertable
// with idempotent semantics via ON CONFLICT deduplication (RF-03, RF-04).
//
// Save receives a domain.VehiclePosition entity and persists it to the database.
// The repository adapter is responsible for:
// - Converting the entity to SQL parameters via a mapper
// - Executing a single parameterized INSERT with ON CONFLICT deduplication
// - Returning a SaveOutcome that distinguishes new insert from duplicate
//
// Error Classification (RF-06):
//
// Save returns a SaveOutcome. The caller (use case) checks:
// - outcome.Success(): true if no error occurred (either insert or duplicate)
// - outcome.WasInserted(): true if a new row was added
// - outcome.WasDuplicate(): true if the event already existed (ON CONFLICT)
// - outcome.Error: contains AppError if persistence failed; caller classifies via IsRecoverable
//
// Offset Commit Implications (RF-05):
//
// Save is called for each validated event. The caller commits the Kafka offset only when:
// - outcome.Success() is true (persistent guarantee satisfied)
// - The event is dead-lettered successfully (alternative persistent guarantee)
type PositionRepository interface {
	// Save persists a position entity via a single parameterized INSERT with ON CONFLICT deduplication.
	//
	// Returns a SaveOutcome that indicates:
	// - outcome.Success() && outcome.WasInserted(): new row was added
	// - outcome.Success() && outcome.WasDuplicate(): event already existed (ON CONFLICT)
	// - !outcome.Success(): persistence failed; outcome.Error contains the error wrapped in AppError
	//   with IsRecoverable set appropriately
	//
	// Args:
	//   position: The validated domain entity
	//   storedAt: The timestamp when this persistence operation occurred (generated by Clock)
	Save(ctx context.Context, position *domain.VehiclePosition, storedAt time.Time) *domain.SaveOutcome

	// Close releases the underlying database connection pool and any other resources.
	Close() error
}
