// TestValidPositionReturns202 verifies that a valid position request returns 202 Accepted
// with the correct response structure.
//
// This is the FIRST test of the Fast Suite and defines the pattern for all subsequent tests.
// It validates:
// - HTTP status code is 202 (Accepted)
// - Response body has correct PositionResponse structure
// - Response.Status == "accepted"
// - Response.TraceID is present and UUID v4
// - Response.VehicleID matches request
// - Response.EventID is present and UUID v4
// - Response.ReceivedAt is ISO 8601 timestamp
// - X-Trace-ID header present in response
// - Event was published async to Kafka (PublishedCount == 1)
//
// Verifies: P2 (Async+202), P4 (4-Timestamps), P7 (RFC9457), P9 (Trace-ID)
// RF: RF-01, RF-02, RF-04, RF-07
//
// Pattern for tests:
// 1. Arrange: Create TestHTTPServer with fakes, build valid PositionRequest
// 2. Act: POST to /api/v1/positions with valid data
// 3. Assert: Verify observable outputs (status, body, headers, fake state)
// DO NOT verify internal implementation details or function call counts
func TestValidPositionReturns202(t *testing.T) {
	// ========== ARRANGE ==========
	// Create test HTTP server with all fakes injected
	server, err := support.NewTestHTTPServer()
	require.NoError(t, err, "failed to create test HTTP server")
	defer server.Stop()

	// Start the server (listens on random port)
	err = server.Start()
	require.NoError(t, err, "failed to start test HTTP server")

	// Build valid position request using Object Mother
	// Valid() returns a builder with all fields set to valid values (VH-001, Manhattan, 10 seconds ago)
	request := mothers.PositionMother{}.Valid().Build()

	// Serialize request to JSON
	reqBody, err := json.Marshal(request)
	require.NoError(t, err, "failed to marshal request")

	// ========== ACT ==========
	// Create HTTP POST request
	httpReq, err := http.NewRequest(
		http.MethodPost,
		server.BaseURL()+"/api/v1/positions",
		bytes.NewReader(reqBody),
	)
	require.NoError(t, err, "failed to create HTTP request")

	// Set headers
	httpReq.Header.Set("Content-Type", "application/json")
	// Note: X-Trace-ID will be generated by middleware if not provided

	// Execute request
	resp, err := http.DefaultClient.Do(httpReq)
	require.NoError(t, err, "failed to send HTTP request")
	defer resp.Body.Close()

	// ========== ASSERT ==========

	// 1. Status code must be 202 (Accepted)
	assert.Equal(t, http.StatusAccepted, resp.StatusCode,
		"expected 202 Accepted, got %d", resp.StatusCode)

	// 2. Parse response body
	var responseBody dto.PositionResponse
	err = json.NewDecoder(resp.Body).Decode(&responseBody)
	if err != nil {
		// If we got an error decoding, let's see what was actually in the body
		resp.Body.Close()
		resp2, _ := http.DefaultClient.Do(httpReq)
		bodyBytes, _ := io.ReadAll(resp2.Body)
		t.Logf("Response body was: %s", string(bodyBytes))
		require.NoError(t, err, "failed to decode response body")
	}

	// 3. Response.Status == "accepted"
	assert.Equal(t, "accepted", responseBody.Status,
		"response status should be 'accepted'")

	// 4. Response.EventID is present and is UUID v4
	assert.NotEmpty(t, responseBody.EventID, "response.event_id should not be empty")
	_, err = uuid.Parse(responseBody.EventID)
	assert.NoError(t, err, "response.event_id should be valid UUID v4: %s", responseBody.EventID)

	// 5. Response.VehicleID matches request
	assert.Equal(t, request.VehicleID, responseBody.VehicleID,
		"response.vehicle_id should match request.vehicle_id")

	// 6. Response.TraceID is present and UUID v4
	assert.NotEmpty(t, responseBody.TraceID, "response.trace_id should not be empty")
	_, err = uuid.Parse(responseBody.TraceID)
	assert.NoError(t, err, "response.trace_id should be valid UUID v4: %s", responseBody.TraceID)

	// 7. Response.ReceivedAt is present and non-zero
	assert.False(t, responseBody.ReceivedAt.IsZero(), "response.received_at should be set")

	// 8. X-Trace-ID response header is present
	traceIDHeader := resp.Header.Get("X-Trace-ID")
	assert.NotEmpty(t, traceIDHeader, "X-Trace-ID response header should not be empty")

	// 9. X-Trace-ID header matches response body TraceID
	assert.Equal(t, responseBody.TraceID, traceIDHeader,
		"X-Trace-ID header should match response.trace_id")

	// 10. Verify event was published to Kafka (async)
	// The publisher is a fake, so we can inspect its state
	kafkaPublisher := server.GetKafkaPublisher()
	assert.Equal(t, 1, kafkaPublisher.PublishedCount(),
		"exactly 1 event should have been published to Kafka")

	// 11. Verify published event has correct data
	publishedEvent := kafkaPublisher.LastPublishedEvent()
	require.NotNil(t, publishedEvent, "published event should not be nil")

	// Verify event structure
	assert.Equal(t, request.VehicleID, publishedEvent.VehicleID().String(),
		"published event vehicle_id should match request")
	assert.Equal(t, responseBody.EventID, publishedEvent.EventID().String(),
		"published event event_id should match response")
}
